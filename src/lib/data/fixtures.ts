export function resolveFirm(ticker: string, year: number) {
  const baseKey = ticker.replace(/2$/, "");
  const firm = FIRMS[baseKey] ?? FIRMS[ticker];
  if (!firm) {
    throw new Error(`Unknown ticker ${ticker}`);
  }
  const override = YEAR_OVERRIDES[`${baseKey}:${year}`];
  return {
    id: firm.id,
    name: override?.name ?? firm.name,
    ticker: override?.ticker ?? firm.ticker,
    description: override?.description ?? firm.description,
  };
}

